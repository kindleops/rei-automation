// The per-migration dossier for the agntei launch chain, generated from the reviewed manifest
// (gateway-chain.manifest.json, built by applying every link on a disposable PostgreSQL) and a static read of each SQL
// file. Read-only: it reads files and writes one markdown document.
//   node scripts/agntei-launch/migration-dossier.mjs > docs/AGNTEI-MIGRATION-DOSSIER.md
import fs from 'node:fs'
import path from 'node:path'
import { SUPERSEDED } from './review-chain.mjs'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..')
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts/agntei-launch/gateway-chain.manifest.json'), 'utf8'))
const read = (f) => (f && fs.existsSync(path.join(ROOT, f)) ? fs.readFileSync(path.join(ROOT, f), 'utf8') : null)
const code = (sql) => sql.replace(/--.*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '')
// statements that run when the migration is applied: function / procedure bodies (as $tag$ ... $tag$) are definitions,
// not apply-time writes; DO blocks do run and are kept
const applyTime = (c) => c.replace(/\bas\s+(\$[a-z_]*\$)[\s\S]*?\1/gi, ' ')
const NOT_A_TABLE = new Set(['or', 'on', 'set', 'must', 'of', 'to', 'the', 'a', 'and', 'are', 'is', 'it', 'this', 'its'])
const SHARED = 11 // the first 11 links are byte-identical on release/cloudflare-production

// tables production's web code reads and writes every day: a change to them is a compatibility question
const PROD_HOT = ['send_queue', 'message_events', 'inbox_thread_state', 'sms_templates', 'campaigns', 'campaign_targets', 'properties', 'master_owners', 'prospects', 'acquisition_opportunities', 'seller_offers', 'system_control', 'phone_numbers']
const objName = (k) => k.replace(/^[a-z_]+:/, '')
const kindOf = (k) => k.split(':')[0]

function scan(sql) {
  const c = code(sql)
  const altered = [...c.matchAll(/alter\s+table\s+(?:if\s+exists\s+)?(?:only\s+)?([a-z_."]+)/gi)].map((m) => m[1].replace(/"/g, ''))
  const indexes = [...c.matchAll(/create\s+(unique\s+)?index\s+(concurrently\s+)?(?:if\s+not\s+exists\s+)?[a-z_"]*\s+on\s+(?:only\s+)?([a-z_."]+)/gi)].map((m) => ({ on: m[3].replace(/"/g, ''), concurrently: Boolean(m[2]) }))
  const triggers = [...c.matchAll(/create\s+(?:or\s+replace\s+)?(?:constraint\s+)?trigger\s+[a-z_"]+[\s\S]*?\son\s+([a-z_."]+)/gi)].map((m) => m[1].replace(/"/g, ''))
  const run = applyTime(c)
  const dml = [...run.matchAll(/\b(update|delete\s+from|insert\s+into|truncate)\s+(?:only\s+)?([a-z_."]+)/gi)].filter((m) => !NOT_A_TABLE.has(m[2].toLowerCase())).map((m) => `${m[1].toLowerCase().replace(/\s+/g, ' ')} ${m[2].replace(/"/g, '')}`)
  const drops = [...run.matchAll(/\bdrop\s+(table|column|function|trigger|view|index|policy|type|schema)\s+(?:if\s+exists\s+)?([a-z_."()]+)/gi)].map((m) => `drop ${m[1].toLowerCase()} ${m[2]}`)
  return {
    altered: [...new Set(altered)], indexes, triggers: [...new Set(triggers)], dml: [...new Set(dml)], drops: [...new Set(drops)],
    lockTimeout: /lock_timeout/i.test(c), statementTimeout: /statement_timeout/i.test(c),
    order: (sql.match(/^--\s*ORDER:.*(?:\n--\s{2,}.*)*/m) || [''])[0].replace(/^--\s*/gm, '').replace(/\s+/g, ' ').trim(),
  }
}

const hot = (t) => PROD_HOT.some((h) => t === h || t === `public.${h}`)
const out = []
const p = (s = '') => out.push(s)
p('# agntei launch: migration dossier')
p()
p(`Generated by \`scripts/agntei-launch/migration-dossier.mjs\` from \`gateway-chain.manifest.json\` (${manifest.migrations.length} migrations, built on PostgreSQL ${manifest.postgres ?? '17'} at ${manifest.commit ?? 'the manifest commit'}) and a static read of each file. Nothing here was applied to production.`)
p()
p('How to read it:')
p('- **Objects** are what the migration adds or replaces, recorded by applying it on a disposable database.')
p('- **Production overlap** names tables production\'s web code uses every day that the file alters, indexes, triggers or writes.')
p('- **Locks**: `ALTER TABLE` takes an ACCESS EXCLUSIVE lock for its duration; a non-concurrent `CREATE INDEX` blocks writes to that table while it builds; a new trigger on a busy table adds work to every write. `lock_timeout` makes the migration give up instead of queueing behind traffic.')
p('- **Data** lists every statement that writes, deletes or drops. "none" means the file only creates or replaces definitions.')
p('- **Existing objects or drift** is decided live, read-only, by `review-chain.mjs` on production (applied, partial, absent, superseded, DRIFT).')
p()
p('| # | Migration | On production branch | Objects (add / replace) | Production overlap | Locks | Data written / dropped | Validation | Rollback |')
p('|---|---|---|---|---|---|---|---|---|')
manifest.migrations.forEach((m, i) => {
  const sql = read(m.file) ?? ''
  const s = scan(sql)
  const adds = m.adds ?? []; const reps = m.replaces ?? []
  const byKind = {}
  for (const k of adds) byKind[kindOf(k)] = (byKind[kindOf(k)] || 0) + 1
  const objects = `${Object.entries(byKind).map(([k, n]) => `${n} ${k}`).join(', ') || 'none'} / ${reps.length} replaced`
  const overlap = [...new Set([...s.altered.filter(hot), ...s.indexes.map((x) => x.on).filter(hot), ...s.triggers.filter(hot), ...s.dml.map((d) => d.split(' ').pop()).filter(hot)])]
  const locks = [s.altered.length ? `ALTER ${s.altered.length}` : '', s.indexes.filter((x) => !x.concurrently).length ? `index ${s.indexes.filter((x) => !x.concurrently).length} (not concurrent)` : '', s.triggers.length ? `trigger on ${s.triggers.join(', ')}` : '', s.lockTimeout ? 'lock_timeout set' : 'no lock_timeout'].filter(Boolean).join('; ')
  const data = [...s.dml, ...s.drops]
  const post = read(m.file.replace(/\.sql$/, '_posttest.sql')) ? 'pretest + posttest' : read(m.pretest) ? 'pretest' : 'none in repo'
  const sup = SUPERSEDED[m.name] ? ` **superseded when Package A is applied**` : ''
  p(`| ${i + 1} | \`${m.name}\`${sup} | ${i < SHARED ? 'yes (byte-identical)' : 'no (gateway only)'} | ${objects} | ${overlap.join(', ') || 'none'} | ${locks} | ${data.length ? data.slice(0, 6).join('; ') + (data.length > 6 ? `; +${data.length - 6} more` : '') : 'none'} | ${post} | ${m.rollback ? 'file' : 'none: restore'} |`)
})
p()
p('## Order and dependencies')
p()
p('The chain is applied strictly in the order above (`scripts/agntei-launch/chain.mjs`, traced from the PostgreSQL 17 proof). `apply-one.mjs` applies only the next reviewed link, after its pretest in a READ ONLY transaction, in one transaction, and reads it back. Where a file states its own order, it is:')
p()
manifest.migrations.forEach((m) => { const o = scan(read(m.file) ?? '').order; if (o) p(`- \`${m.name}\`: ${o.slice(0, 400)}`) })
p()
p('## Package A (production-only migrations)')
p()
p('`PROPOSED_20261020120000_research_event_budget_ceilings` and `PROPOSED_20261020120100_research_package_schedules` exist only on `release/cloudflare-production`. If production carries the ceilings migration, `PROPOSED_20261013161000_conversation_decide_event_budget` is superseded: the reviewer reads it so, `apply-one` refuses it, and the PostgreSQL 17 proof applies the other 17 pending links on top and re-runs Package A\'s posttest successfully. The schedules seed is independent of the chain (born disabled; upserts by name).')
p()
p('## Rollback and recovery')
p()
p('- Every link with a rollback file can be reversed in reverse chain order; the migration-test runner proves each rollback restores the exact pre-link schema fingerprint (`scripts/db/run-migration-test.mjs`).')
p('- Before the first apply: a Supabase point-in-time restore marker, or `pg_dump --schema-only` plus a data dump of the schemas the chain touches (`agent`, `action_gateway`, `public` tables listed above).')
p('- A link that fails rolls back on its own (one transaction). A link that applies but misbehaves is reversed with its rollback file, then the review is re-run before anything else.')
print()
function print() { process.stdout.write(out.join('\n') + '\n') }
