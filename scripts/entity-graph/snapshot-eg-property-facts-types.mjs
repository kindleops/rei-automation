#!/usr/bin/env node
/**
 * Snapshot the column types eg_property_facts copies (read-only information_schema).
 * Writes apps/api/src/lib/domain/entity-graph/eg-property-facts-types.js.
 * Usage: LC_RO_ENTITY_GRAPH_DB_URL_FILE=<0600 file> node scripts/entity-graph/snapshot-eg-property-facts-types.mjs
 * Credential: LC_RO_ENTITY_GRAPH_DB_URL_FILE (the role-enforced read-only diagnostics credential; scripts/lib/prod-db-credentials.mjs).
 */
import fs from 'node:fs'
import path from 'node:path'
import { connectReadOnlyDiagnostics } from '../lib/prod-db-credentials.mjs'

const client = await connectReadOnlyDiagnostics({ purpose: 'entity_graph', applicationName: 'lc-eg-facts-types' })
await client.query("set statement_timeout = '30s'; set default_transaction_read_only = on")
const { rows } = await client.query(`
  select table_name, column_name, data_type, udt_name
    from information_schema.columns
   where table_schema = 'public'
     and table_name in ('v_entity_graph_properties', 'master_owners', 'property_acquisition_scores')
   order by table_name, ordinal_position`)
await client.end()
const pgType = (r) => {
  if (r.data_type === 'ARRAY') return `${r.udt_name.replace(/^_/, '')}[]`.replace(/^int4/, 'integer').replace(/^int8/, 'bigint').replace(/^float8/, 'double precision')
  if (r.data_type === 'USER-DEFINED') return r.udt_name
  return r.data_type
}
const out = {}
for (const r of rows) {
  out[r.table_name] = out[r.table_name] || {}
  out[r.table_name][r.column_name] = pgType(r)
}
const file = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../apps/api/src/lib/domain/entity-graph/eg-property-facts-types.js')
const body = `/**\n * GENERATED by scripts/entity-graph/snapshot-eg-property-facts-types.mjs (read-only information_schema, prod).\n * Column types the eg_property_facts read model copies. Re-run after a source column changes type.\n */\nexport const SOURCE_COLUMN_TYPES = Object.freeze(${JSON.stringify(out, null, 2)})\n`
fs.writeFileSync(file, body)
console.log(`wrote ${file}: ${Object.entries(out).map(([t, c]) => `${t}=${Object.keys(c).length}`).join(' ')}`)
