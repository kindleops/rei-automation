#!/usr/bin/env node
/**
 * Profile the property columns the Entity Graph Overview charts (read-only, prod).
 * Writes apps/api/src/lib/domain/entity-graph/entity-graph-overview-profile.js:
 *   { column: { type, known, distinct?, min?, max?, p02?, p98?, integer? } }
 * over the UNIVERSE (canary fixtures excluded). The Overview uses it for two
 * things only — never for a count:
 *   - cardinality: a text column with > 500 distinct values is charted as
 *     coverage + distinct count (bars of 100k addresses are not a chart);
 *   - fixed histogram edges for numeric / date columns with no curated edges,
 *     so a bin means the same range in every cohort.
 * The spec's eg_field_profile (re-profiled at facts refresh) replaces this
 * snapshot once the read model is live.
 *
 * Usage: node scripts/entity-graph/profile-overview-fields.mjs
 * Credential: LC_RO_ENTITY_GRAPH_DB_URL_FILE (the role-enforced read-only diagnostics credential; scripts/lib/prod-db-credentials.mjs).
 */
import fs from 'node:fs'
import path from 'node:path'
import { connectReadOnlyDiagnostics } from '../lib/prod-db-credentials.mjs'

const client = await connectReadOnlyDiagnostics({ purpose: 'entity_graph', applicationName: 'lc-eg-profile-fields', statementTimeoutMs: 60_000 })
await client.query("set statement_timeout = '60s'; set default_transaction_read_only = on")

const { rows: cols } = await client.query(`
  select v.column_name, v.data_type, v.udt_name, (p.column_name is not null) as on_properties
    from information_schema.columns v
    left join information_schema.columns p
      on p.table_schema = 'public' and p.table_name = 'properties' and p.column_name = v.column_name
   where v.table_schema = 'public' and v.table_name = 'v_entity_graph_properties'
   order by v.ordinal_position`)

const SKIP = new Set(['raw_payload_json', 'map_image', 'satellite_image', 'streetview_image', 'row_hash', 'upsert_key'])
const isNum = (t) => /^(integer|bigint|smallint|numeric|real|double precision)$/.test(t)
const isDate = (t) => /^(date|timestamp with time zone|timestamp without time zone)$/.test(t)
const q = (c) => `"${c}"`

const out = {}
const batches = []
const usable = cols.filter((c) => !SKIP.has(c.column_name) && c.data_type !== 'jsonb' && c.data_type !== 'ARRAY')
for (let i = 0; i < usable.length; i += 12) batches.push(usable.slice(i, i + 12))

const t0 = Date.now()
for (const batch of batches) {
  const onBase = batch.every((c) => c.on_properties)
  const rel = onBase ? 'public.properties' : 'public.v_entity_graph_properties'
  const exprs = []
  for (const c of batch) {
    const k = c.column_name
    exprs.push(`count(${q(k)}) as "${k}__known"`)
    if (isNum(c.data_type)) {
      exprs.push(`min(${q(k)})::float8 as "${k}__min"`, `max(${q(k)})::float8 as "${k}__max"`)
      exprs.push(`percentile_disc(0.02) within group (order by ${q(k)})::float8 as "${k}__p02"`)
      exprs.push(`percentile_disc(0.98) within group (order by ${q(k)})::float8 as "${k}__p98"`)
      exprs.push(`bool_and(${q(k)} = trunc(${q(k)})) as "${k}__int"`)
    } else if (isDate(c.data_type)) {
      exprs.push(`min(${q(k)})::date::text as "${k}__min"`, `max(${q(k)})::date::text as "${k}__max"`)
      exprs.push(`percentile_disc(0.02) within group (order by ${q(k)})::date::text as "${k}__p02"`)
      exprs.push(`percentile_disc(0.98) within group (order by ${q(k)})::date::text as "${k}__p98"`)
    } else if (c.data_type !== 'boolean') {
      exprs.push(`count(distinct ${q(k)}) as "${k}__distinct"`)
    }
  }
  const sql = `select ${exprs.join(', ')} from ${rel} where property_id not like 'canaryprop%'`
  const { rows: [r] } = await client.query(sql)
  for (const c of batch) {
    const k = c.column_name
    const entry = { type: c.data_type, known: Number(r[`${k}__known`]) }
    if (r[`${k}__distinct`] !== undefined) entry.distinct = Number(r[`${k}__distinct`])
    for (const s of ['min', 'max', 'p02', 'p98']) if (r[`${k}__${s}`] !== undefined && r[`${k}__${s}`] !== null) entry[s] = r[`${k}__${s}`]
    if (r[`${k}__int`] !== undefined && r[`${k}__int`] !== null) entry.integer = Boolean(r[`${k}__int`])
    out[k] = entry
  }
}
const { rows: [{ n }] } = await client.query(`select count(*)::int as n from public.properties where property_id not like 'canaryprop%'`)
await client.end()

const file = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../../apps/api/src/lib/domain/entity-graph/entity-graph-overview-profile.js')
const body = `/**
 * GENERATED by scripts/entity-graph/profile-overview-fields.mjs (read-only, prod, ${new Date().toISOString().slice(0, 10)}).
 * Universe profile of v_entity_graph_properties (${n} properties, canaries excluded) — cardinality and
 * histogram ranges ONLY. Never a count: every number the Overview shows is computed per request.
 */
export const OVERVIEW_PROFILE_UNIVERSE = ${n}
export const OVERVIEW_COLUMN_PROFILE = Object.freeze(${JSON.stringify(out, null, 1)})
`
fs.writeFileSync(file, body)
console.log(`wrote ${file}: ${Object.keys(out).length} columns in ${Date.now() - t0} ms`)
