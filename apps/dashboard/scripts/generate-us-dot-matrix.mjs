#!/usr/bin/env node
/**
 * Generates src/views/home/us-dot-matrix.ts — the dot-matrix United States drawn
 * on Home — from the real state boundaries in us-atlas (US Census Bureau
 * cartographic boundaries, 1:10m, pre-projected to Albers USA with Alaska and
 * Hawaii as insets; ISC licence).
 *
 * The package is not a dependency: fetch it once and point this script at it.
 *
 *   npm pack us-atlas@3 && tar xzf us-atlas-3.0.1.tgz
 *   node scripts/generate-us-dot-matrix.mjs package/states-albers-10m.json
 *
 * Output is a hexagonal grid of points sampled strictly inside the true state
 * polygons (holes respected), each tagged with its state, plus a label anchor
 * per state at the mean of its dots. No business data is involved.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const source = process.argv[2]
if (!source) {
  console.error('usage: node scripts/generate-us-dot-matrix.mjs <states-albers-10m.json>')
  process.exit(1)
}

const SPACING = 11.5

const ABBR = {
  Alabama: 'AL', Alaska: 'AK', Arizona: 'AZ', Arkansas: 'AR', California: 'CA', Colorado: 'CO',
  Connecticut: 'CT', Delaware: 'DE', 'District of Columbia': 'DC', Florida: 'FL', Georgia: 'GA',
  Hawaii: 'HI', Idaho: 'ID', Illinois: 'IL', Indiana: 'IN', Iowa: 'IA', Kansas: 'KS', Kentucky: 'KY',
  Louisiana: 'LA', Maine: 'ME', Maryland: 'MD', Massachusetts: 'MA', Michigan: 'MI', Minnesota: 'MN',
  Mississippi: 'MS', Missouri: 'MO', Montana: 'MT', Nebraska: 'NE', Nevada: 'NV', 'New Hampshire': 'NH',
  'New Jersey': 'NJ', 'New Mexico': 'NM', 'New York': 'NY', 'North Carolina': 'NC', 'North Dakota': 'ND',
  Ohio: 'OH', Oklahoma: 'OK', Oregon: 'OR', Pennsylvania: 'PA', 'Rhode Island': 'RI',
  'South Carolina': 'SC', 'South Dakota': 'SD', Tennessee: 'TN', Texas: 'TX', Utah: 'UT', Vermont: 'VT',
  Virginia: 'VA', Washington: 'WA', 'West Virginia': 'WV', Wisconsin: 'WI', Wyoming: 'WY',
}

const topology = JSON.parse(fs.readFileSync(source, 'utf8'))

// ── Minimal TopoJSON decoding (quantized, delta-encoded arcs) ───────────────
const { scale = [1, 1], translate = [0, 0] } = topology.transform ?? {}
const arcs = topology.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
  })
})
const arcPoints = (index) => (index >= 0 ? arcs[index] : [...arcs[~index]].reverse())
const ring = (indices) => indices.flatMap((index, i) => {
  const points = arcPoints(index)
  return i === 0 ? points : points.slice(1)
})

const states = topology.objects.states.geometries
  .map((geometry) => {
    const polygons = geometry.type === 'Polygon' ? [geometry.arcs] : geometry.type === 'MultiPolygon' ? geometry.arcs : []
    const rings = polygons.flatMap((polygon) => polygon.map(ring))
    const bounds = rings.map((r) => {
      const xs = r.map((p) => p[0])
      const ys = r.map((p) => p[1])
      return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]
    })
    return { name: geometry.properties.name, abbr: ABBR[geometry.properties.name], rings, bounds }
  })
  .filter((state) => state.abbr)

// Even-odd over every ring of the state: holes (lakes, enclaves) fall out naturally.
const inside = (x, y, state) => {
  let hit = false
  state.rings.forEach((r, k) => {
    const [x0, y0, x1, y1] = state.bounds[k]
    if (x < x0 || x > x1 || y < y0 || y > y1) return
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i]
      const [xj, yj] = r[j]
      if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit
    }
  })
  return hit
}

const [width, height] = [975, 610]
const dots = []
for (let row = 0, y = SPACING / 2; y < height; y += SPACING * 0.866, row++) {
  for (let x = SPACING / 2 + (row % 2) * (SPACING / 2); x < width; x += SPACING) {
    const index = states.findIndex((state) => inside(x, y, state))
    if (index >= 0) dots.push([Math.round(x * 10), Math.round(y * 10), index])
  }
}

const anchors = states.map((state, index) => {
  const own = dots.filter((dot) => dot[2] === index)
  if (own.length === 0) {
    // A state too small for the grid (DC, RI at this spacing) anchors on its bounds.
    const [x0, y0, x1, y1] = state.bounds[0]
    return { abbr: state.abbr, name: state.name, x: Math.round((x0 + x1) / 2), y: Math.round((y0 + y1) / 2) }
  }
  const x = own.reduce((sum, dot) => sum + dot[0], 0) / own.length / 10
  const y = own.reduce((sum, dot) => sum + dot[1], 0) / own.length / 10
  return { abbr: state.abbr, name: state.name, x: Math.round(x), y: Math.round(y) }
})

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/views/home/us-dot-matrix.ts')
const body = `// GENERATED by scripts/generate-us-dot-matrix.mjs from us-atlas@3 states-albers-10m
// (US Census Bureau cartographic boundaries, Albers USA projection, ISC licence).
// Do not edit by hand; regenerate instead.

export const US_VIEWBOX = { width: ${width}, height: ${height} } as const

/** Label anchor per state: the mean of its dots, in viewBox units. */
export const US_STATES: ReadonlyArray<{ abbr: string; name: string; x: number; y: number }> = ${JSON.stringify(anchors)}

/** Flat triples: x * 10, y * 10, index into US_STATES. ${dots.length} dots at ${SPACING}-unit hex spacing. */
export const US_DOTS: ReadonlyArray<number> = [${dots.flat().join(',')}]
`
fs.writeFileSync(out, body)
console.log(`wrote ${dots.length} dots for ${anchors.length} states to ${path.relative(process.cwd(), out)} (${(body.length / 1024).toFixed(1)} KB)`)
