/**
 * ENTITY GRAPH · eg_property_facts DDL — GENERATED from the facts registry
 * (entity-graph-facts.js) so the table can never carry a column the code does
 * not compute, or miss one it does. The committed PROPOSED migration is this
 * function's output (test: entity-graph-facts-ddl.test.mjs). Regenerate with
 *   node --import ./tests/register-aliases.mjs ../../scripts/entity-graph/generate-eg-property-facts-sql.mjs
 */
import { COMPUTED_FACTS, PLAIN_FACT_COLUMNS, plainColumnType } from './entity-graph-facts.js'

export const FACTS_TABLE_NAME = 'eg_property_facts'

/**
 * (col, property_id) btree for keyset sort — the columns an operator sorts by
 * most (default + outreach + company + the record columns). Every other column
 * still sorts exactly: a top-N over the ~240 MB table instead of an index walk.
 */
export const FACTS_SORT_INDEXES = Object.freeze([
  // computed
  'sms_sort', 'sms_status', 'last_contact_at', 'pipeline_stage', 'pipeline_status', 'conversation_stage', 'conversation_status',
  'last_message_at', 'campaign_count', 'contact_candidate_phones', 'equity_known_pct', 'equity_known_amount', 'lien_count',
  'filing_count', 'last_sale_on', 'distress_signal_count', 'asset_type', 'zip_code', 'owner_buyer_purchases',
  'company_status_class', 'company_dissolution_date', 'company_incorporation_date', 'person_age', 'owner_priority_score',
  // plain
  'property_address_full', 'market', 'estimated_value', 'units_count', 'owner_name', 'year_built', 'building_square_feet',
  'total_bedrooms', 'total_baths', 'lot_square_feet', 'property_address_county_name', 'property_address_city',
  'property_address_state', 'property_type', 'rec_mortgage_count', 'rec_mortgage_balance', 'rec_first_rate', 'rec_first_lender',
  'rec_last_sale_date', 'ownership_years', 'total_loan_balance', 'sale_date',
])
/** text[] membership filters (signal / lien / filing type checklists). */
export const FACTS_GIN_INDEXES = Object.freeze(['signal_labels', 'lien_types', 'filing_types'])
/** `ilike '%…%'` filters the rail uses (market, market region, owner, county). */
export const FACTS_TRGM_INDEXES = Object.freeze(['market', 'market_region', 'owner_name', 'property_address_county_name'])

/**
 * Every column, in table order: property_id, plain (view) columns, computed facts.
 * `addenda: false` = the base 20261009 migration only (facts carrying an
 * `addendum` arrive by their own ALTER TABLE migration — generateFactsAddendumSql).
 */
export function factsTableColumns({ addenda = true } = {}) {
  const plain = PLAIN_FACT_COLUMNS.filter((c) => c !== 'property_id' && plainColumnType(c))
  const computed = COMPUTED_FACTS.filter((f) => addenda || !f.addendum).map((f) => ({ col: f.col, pg: f.pg, ...(f.addendum ? { addendum: f.addendum } : {}) }))
  return [
    { col: 'property_id', pg: 'text', notNull: true },
    ...plain.map((c) => ({ col: c, pg: plainColumnType(c), plain: true })),
    ...computed,
  ]
}

const shortName = (col) => col.length > 40 ? `${col.slice(0, 32)}_${Math.abs([...col].reduce((h, ch) => (h * 31 + ch.charCodeAt(0)) | 0, 7)).toString(36).slice(0, 6)}` : col

export function generateFactsMigrationSql() {
  const cols = factsTableColumns({ addenda: false })
  const names = new Set(cols.map((c) => c.col))
  for (const i of [...FACTS_SORT_INDEXES, ...FACTS_GIN_INDEXES, ...FACTS_TRGM_INDEXES]) {
    if (!names.has(i)) throw new Error(`index on unknown facts column ${i}`)
  }
  const lines = []
  lines.push(`-- PROPOSED — NOT APPLIED. GENERATED by apps/api/src/lib/domain/entity-graph/entity-graph-facts-ddl.js; do not hand-edit.`)
  lines.push(`-- Entity Graph property facts read model (EG9 P0 eg_property_facts + eg_refresh_log).`)
  lines.push(`--`)
  lines.push(`-- One row per property with every value a property grid column shows / sorts / filters on:`)
  lines.push(`--   ${cols.filter((c) => c.plain).length} plain columns copied from v_entity_graph_properties (same names, same types)`)
  lines.push(`--   ${COMPUTED_FACTS.filter((f) => !f.addendum).length} computed facts (SMS eligibility + reason, last contact, pipeline / conversation stage + status,`)
  lines.push(`--   known equity, liens vs filings, signals, owning-company registry status, owner / person / contact / ZIP / engine fields)`)
  lines.push(`-- Computed facts are written by the API refresh job (entity-graph-facts-refresh.js) with the SAME JS functions the`)
  lines.push(`-- grid cells render from — this migration creates storage only; it computes nothing.`)
  lines.push(`-- Estimated size (prod 2026-10-09, 0.5% sample): ~1.0 KB plain + ~0.3 KB computed per row × 176.6K ≈ 240 MB heap,`)
  lines.push(`--   + ${FACTS_SORT_INDEXES.length} (col, property_id) btrees (~5–8 MB each) + ${FACTS_GIN_INDEXES.length} GIN + ${FACTS_TRGM_INDEXES.length} trigram.`)
  lines.push(`-- Reads: service role only (direct-PG pool). Writes: the refresh job only.`)
  lines.push(`-- Apply via the MCP channel (migration history is broken — memory 09-04); run the pretest first.`)
  lines.push(`--`)
  lines.push(`-- After apply (owner):`)
  lines.push(`--   1. EG_FACTS_REFRESH_ENABLED=true on the API, then POST /api/internal/entity-graph/facts-refresh?mode=full once (cron auth).`)
  lines.push(`--      Entity Graph keeps the live computation until that run logs status 'ok' in eg_refresh_log.`)
  lines.push(`--   2. Worker cron (infra/cloudflare/worker/index.ts, its own flag CRON_EG_FACTS_REFRESH_ENABLED, send-incapable):`)
  lines.push(`--        */5 0-11,15-23 * * *  POST …/facts-refresh?mode=incremental   (skips the 11:15–14:30 UTC heavy-read blackout)`)
  lines.push(`--        30 9 * * *            POST …/facts-refresh?mode=full          (after refresh_entity_graph_read_model, 09:17 UTC)`)
  lines.push(`--   3. Kill switch without dropping anything: EG_FACTS_TABLE_READS=off (reads fall back to the live computation).`)
  lines.push(``)
  lines.push(`create extension if not exists pg_trgm;`)
  lines.push(``)
  lines.push(`create table if not exists public.eg_refresh_log (`)
  lines.push(`  id           bigserial primary key,`)
  lines.push(`  name         text not null,`)
  lines.push(`  mode         text not null check (mode in ('full', 'incremental')),`)
  lines.push(`  status       text not null check (status in ('running', 'ok', 'failed')),`)
  lines.push(`  started_at   timestamptz not null default now(),`)
  lines.push(`  finished_at  timestamptz,`)
  lines.push(`  rows         integer,`)
  lines.push(`  watermark    timestamptz,`)
  lines.push(`  error        text,`)
  lines.push(`  detail       jsonb not null default '{}'::jsonb`)
  lines.push(`);`)
  lines.push(`create index if not exists eg_refresh_log_name_status_idx on public.eg_refresh_log (name, status, finished_at desc);`)
  lines.push(``)
  lines.push(`create table if not exists public.${FACTS_TABLE_NAME} (`)
  const defs = cols.map((c) => `  "${c.col}" ${c.pg}${c.notNull ? ' not null primary key' : ''}`)
  defs.push(`  "refreshed_at" timestamptz not null default now()`)
  lines.push(defs.join(',\n'))
  lines.push(`);`)
  lines.push(``)
  lines.push(`-- keyset sort: (col, property_id), both ascending (scanned backward for desc) — the shape entity-graph-facts-query expects`)
  for (const c of FACTS_SORT_INDEXES) lines.push(`create index if not exists egpf_${shortName(c)}_k on public.${FACTS_TABLE_NAME} ("${c}", "property_id");`)
  for (const c of FACTS_GIN_INDEXES) lines.push(`create index if not exists egpf_${shortName(c)}_gin on public.${FACTS_TABLE_NAME} using gin ("${c}");`)
  for (const c of FACTS_TRGM_INDEXES) lines.push(`create index if not exists egpf_${shortName(c)}_trgm on public.${FACTS_TABLE_NAME} using gin ("${c}" gin_trgm_ops);`)
  lines.push(`create index if not exists egpf_refreshed_at on public.${FACTS_TABLE_NAME} (refreshed_at);`)
  lines.push(``)
  lines.push(`alter table public.${FACTS_TABLE_NAME} enable row level security;`)
  lines.push(`alter table public.eg_refresh_log enable row level security;`)
  lines.push(`revoke all on public.${FACTS_TABLE_NAME} from anon, authenticated;`)
  lines.push(`revoke all on public.eg_refresh_log from anon, authenticated;`)
  lines.push(`revoke all on sequence public.eg_refresh_log_id_seq from anon, authenticated;`)
  lines.push(``)
  lines.push(`comment on table public.${FACTS_TABLE_NAME} is 'Entity Graph property facts read model (EG9 P0). Written only by the API refresh job; values "as of" the last eg_refresh_log row with status ok.';`)
  lines.push(``)
  return `${lines.join('\n')}\n`
}

export function generateFactsRollbackSql() {
  return [
    `-- ROLLBACK for PROPOSED_20261009180000_eg_property_facts.sql. Drops the read model only; no source table is touched.`,
    `-- Entity Graph falls back to the live computation automatically (entity-graph-facts-query.js factsState).`,
    `drop table if exists public.${FACTS_TABLE_NAME};`,
    `drop table if exists public.eg_refresh_log;`,
    ``,
  ].join('\n')
}

/**
 * Rollback-txn pretest (memory: "rollback-txn migration pretest"): applies the
 * migration inside a transaction, proves the shapes the code relies on, and
 * ROLLS BACK. Safe to run on prod: it creates new objects only and keeps no row.
 */
export function generateFactsPretestSql() {
  const migration = generateFactsMigrationSql()
  const cols = factsTableColumns({ addenda: false })
  return [
    `-- PRETEST for PROPOSED_20261009180000_eg_property_facts.sql — runs the migration in a transaction and ROLLS BACK.`,
    `-- Expect: every NOTICE 'ok …' and a final ROLLBACK. Any exception = do not apply.`,
    `begin;`,
    `set local statement_timeout = '60s';`,
    `set local lock_timeout = '3s';`,
    migration,
    `do $pretest$`,
    `declare n int; t text;`,
    `begin`,
    `  -- 1. every registry column exists with its declared type`,
    `  select count(*) into n from information_schema.columns where table_schema = 'public' and table_name = '${FACTS_TABLE_NAME}';`,
    `  if n <> ${cols.length + 1} then raise exception 'expected ${cols.length + 1} columns, found %', n; end if;`,
    `  raise notice 'ok columns: %', n;`,
    `  -- 2. every keyset index has the (col, property_id) shape the sort detector requires`,
    `  select count(*) into n from pg_index i join pg_class c on c.oid = i.indrelid join pg_attribute a2 on a2.attrelid = i.indrelid and a2.attnum = i.indkey[1]`,
    `   where c.relname = '${FACTS_TABLE_NAME}' and i.indnkeyatts >= 2 and a2.attname = 'property_id' and i.indpred is null;`,
    `  if n < ${FACTS_SORT_INDEXES.length} then raise exception 'expected ${FACTS_SORT_INDEXES.length} keyset indexes, found %', n; end if;`,
    `  raise notice 'ok keyset indexes: %', n;`,
    `  -- 3. a facts row round-trips through jsonb_populate_recordset (the refresh job's write path)`,
    `  insert into public.${FACTS_TABLE_NAME} select * from jsonb_populate_recordset(null::public.${FACTS_TABLE_NAME},`,
    `    '[{"property_id":"pretest1","sms_eligible":true,"sms_status":"eligible","sms_sort":"0","signal_labels":["Vacant","Probate"],"company_status_class":"dissolved","last_contact_at":"2026-10-01T12:00:00Z","refreshed_at":"2026-10-09T00:00:00Z"},`,
    `      {"property_id":"pretest2","sms_eligible":false,"sms_status":"missing_phone","sms_sort":"1 missing_phone","company_status_class":"not_a_company","refreshed_at":"2026-10-09T00:00:00Z"}]'::jsonb);`,
    `  select count(*) into n from public.${FACTS_TABLE_NAME} where "sms_sort" is not null and ("sms_sort", "property_id") > ('0', 'pretest1');`,
    `  if n <> 1 then raise exception 'keyset predicate returned %', n; end if;`,
    `  select count(*) into n from public.${FACTS_TABLE_NAME} where "signal_labels" && array['Probate'];`,
    `  if n <> 1 then raise exception 'token overlap returned %', n; end if;`,
    `  raise notice 'ok write + keyset + overlap';`,
    `  -- 4. the API's "as of" source`,
    `  insert into public.eg_refresh_log (name, mode, status, finished_at, rows) values ('${FACTS_TABLE_NAME}', 'full', 'ok', now(), 2);`,
    `  select status into t from public.eg_refresh_log where name = '${FACTS_TABLE_NAME}' order by id desc limit 1;`,
    `  if t <> 'ok' then raise exception 'refresh log not readable'; end if;`,
    `  -- 5. not exposed to the browser roles`,
    `  if has_table_privilege('anon', 'public.${FACTS_TABLE_NAME}', 'select') or has_table_privilege('authenticated', 'public.${FACTS_TABLE_NAME}', 'select') then raise exception 'facts table readable by anon/authenticated'; end if;`,
    `  raise notice 'ok privileges';`,
    `end`,
    `$pretest$;`,
    `rollback;`,
    ``,
  ].join('\n')
}

/* ── addenda: facts added after the base migration ─────────────────────────────── */

/** Addendum ids, in registry order. */
export function factsAddenda() {
  return [...new Set(COMPUTED_FACTS.map((f) => f.addendum).filter(Boolean))]
}

/** (col, property_id) keyset indexes an addendum brings. */
export const FACTS_ADDENDUM_SORT_INDEXES = Object.freeze({
  '20261010200000_eg_property_facts_field_accuracy': Object.freeze(['property_type_class', 'property_type_group']),
})

/** ALTER TABLE … ADD COLUMN IF NOT EXISTS for one addendum (idempotent; storage only — the refresh fills it). */
export function generateFactsAddendumSql(addendum) {
  const cols = factsTableColumns().filter((c) => c.addendum === addendum)
  if (!cols.length) throw new Error(`unknown facts addendum ${addendum}`)
  const idx = FACTS_ADDENDUM_SORT_INDEXES[addendum] || []
  for (const i of idx) if (!cols.some((c) => c.col === i)) throw new Error(`addendum index on unknown column ${i}`)
  return [
    `-- PROPOSED — NOT APPLIED. GENERATED by apps/api/src/lib/domain/entity-graph/entity-graph-facts-ddl.js; do not hand-edit.`,
    `-- Addendum ${addendum} to PROPOSED_20261009180000_eg_property_facts.sql (apply that first).`,
    `-- Adds ${cols.length} computed fact columns (storage only). The API refresh job writes only the columns the table has,`,
    `-- so this applies before or after a deploy. Reads of these columns stay on the live computation until a full refresh`,
    `-- that wrote them has logged ok (entity-graph-facts-query.js factsState: columns + their addendum's backfill).`,
    `-- After apply: one full refresh (POST /api/internal/entity-graph/facts-refresh?mode=full, or`,
    `--   node scripts/entity-graph/backfill-eg-property-facts.mjs).`,
    `-- Size: ${cols.length} short text columns ≈ 70 B/row × 176.6K ≈ 12 MB, + ${idx.length} btrees (~5 MB each).`,
    `begin;`,
    `set local lock_timeout = '3s';`,
    ...cols.map((c) => `alter table public.${FACTS_TABLE_NAME} add column if not exists "${c.col}" ${c.pg};`),
    ...idx.map((c) => `create index if not exists egpf_${shortName(c)}_k on public.${FACTS_TABLE_NAME} ("${c}", "property_id");`),
    `commit;`,
    ``,
  ].join('\n')
}

export function generateFactsAddendumRollbackSql(addendum) {
  const cols = factsTableColumns().filter((c) => c.addendum === addendum)
  if (!cols.length) throw new Error(`unknown facts addendum ${addendum}`)
  return [
    `-- ROLLBACK for PROPOSED_${addendum}.sql. Drops the addendum columns (and their indexes) only; reads fall back to the live computation.`,
    `begin;`,
    `set local lock_timeout = '3s';`,
    ...cols.map((c) => `alter table public.${FACTS_TABLE_NAME} drop column if exists "${c.col}";`),
    `commit;`,
    ``,
  ].join('\n')
}
