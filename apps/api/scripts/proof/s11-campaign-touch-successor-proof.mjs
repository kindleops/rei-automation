/**
 * Builds the rolled-back production proof for migration
 * 20260930160000_campaign_touch_successor_actions.
 *
 *   node scripts/proof/s11-campaign-touch-successor-proof.mjs
 *     -> writes scripts/proof/s11-campaign-touch-successor-proof.sql
 *
 * The SQL is ONE `DO` statement: it applies the migration inside the statement,
 * exercises it against the real stuck retries, then RAISES with the results, so
 * the statement aborts and nothing persists. A single statement matters: an
 * explicit BEGIN that errors can leave an aborted transaction holding the
 * index locks on a pooled connection; an aborted DO statement cannot.
 * Nothing here can reach a provider: these tables have no network triggers.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../../../..');
const migration = fs.readFileSync(
  path.join(repo, 'supabase/migrations/20260930160000_campaign_touch_successor_actions.sql'),
  'utf8',
);

// The migration's statements, minus its own transaction and header comments.
const body = migration
  .split('\n')
  .filter((line) => !/^(BEGIN|COMMIT);\s*$/.test(line) && !/^--/.test(line))
  .join('\n')
  .trim();

const key = (target, touch, action) =>
  `'lck_v1:campaign_touch:' || encode(extensions.digest('lck_v1|campaign_touch|' || ${target} || '|' || ${touch} || '|' || ${action}, 'sha256'), 'hex')`;

const sql = `-- §11 campaign-touch successor PROOF against the real database. ROLLS BACK.
-- Generated by scripts/proof/s11-campaign-touch-successor-proof.mjs; do not edit.
DO $proof$
DECLARE
  v_row record; v_q record; v_del record;
  v_lin jsonb; v_root_id uuid; v_t uuid := gen_random_uuid();
  k1 text; k2 text; k3 text; kD text;
  r1 jsonb; r1b jsonb; r1c jsonb; a1 jsonb; r_root jsonb; a_root jsonb;
  rD jsonb; rNew jsonb; rNew2 jsonb; rr jsonb;
  tally jsonb := '{}'::jsonb; tk text;
BEGIN
${body}

  -- 1. a real looping retry and its carrier-failed original
  SELECT q.id, q.campaign_target_id, q.touch_number, q.campaign_id, q.thread_key, q.to_phone_number
    INTO v_row FROM public.send_queue q
   WHERE q.queue_status = 'queued' AND q.metadata->>'skip_reason' = 'logical_communication_store_error'
   ORDER BY q.scheduled_for LIMIT 1;
  k1 := ${key('v_row.campaign_target_id', 'v_row.touch_number', '1')};
  k2 := ${key('v_row.campaign_target_id', 'v_row.touch_number', '2')};
  k3 := ${key('v_row.campaign_target_id', 'v_row.touch_number', '3')};
  v_lin := jsonb_build_object('campaign_target_id', v_row.campaign_target_id, 'touch_number', v_row.touch_number::text,
    'campaign_id', v_row.campaign_id, 'thread_key', v_row.thread_key, 'to_phone_number', v_row.to_phone_number);
  SELECT id INTO v_root_id FROM public.seller_logical_communications WHERE logical_key = k1;

  r1     := public.seller_logical_communication_get_or_create(k2, 'lck_v1', 'campaign_touch', v_lin, '{}'::jsonb);
  r1b    := public.seller_logical_communication_get_or_create(k2, 'lck_v1', 'campaign_touch', v_lin, '{}'::jsonb);
  r1c    := public.seller_logical_communication_get_or_create(k3, 'lck_v1', 'campaign_touch', v_lin, '{}'::jsonb);
  a1     := public.seller_communication_attempt_allocate((r1->>'logical_communication_id')::uuid, 'textgrid', 'proof-row', 'proof-token', '{}'::jsonb);
  r_root := public.seller_logical_communication_get_or_create(k1, 'lck_v1', 'campaign_touch', v_lin, '{}'::jsonb);
  a_root := public.seller_communication_attempt_allocate(v_root_id, 'textgrid', 'proof-row-root', 'proof-token-root', '{}'::jsonb);

  -- 2. a DELIVERED campaign touch must never gain a successor
  SELECT c.id, c.campaign_target_id, c.touch_number INTO v_del
    FROM public.seller_logical_communications c
    JOIN public.seller_communication_attempts a ON a.logical_communication_id = c.id
    JOIN public.message_events m ON m.provider_message_sid = a.provider_message_id
   WHERE c.communication_type = 'campaign_touch' AND m.delivery_status = 'delivered'
   LIMIT 1;
  kD := ${key('v_del.campaign_target_id', 'v_del.touch_number', '2')};
  rD := public.seller_logical_communication_get_or_create(kD, 'lck_v1', 'campaign_touch',
          jsonb_build_object('campaign_target_id', v_del.campaign_target_id, 'touch_number', v_del.touch_number::text), '{}'::jsonb);

  -- 3. a brand-new touch still gets its root; a second action while it is unsettled is refused
  rNew  := public.seller_logical_communication_get_or_create(${key('v_t', "'1'", '1')},
             'lck_v1', 'campaign_touch', jsonb_build_object('campaign_target_id', v_t, 'touch_number', '1'), '{}'::jsonb);
  rNew2 := public.seller_logical_communication_get_or_create(${key('v_t', "'1'", '2')},
             'lck_v1', 'campaign_touch', jsonb_build_object('campaign_target_id', v_t, 'touch_number', '1'), '{}'::jsonb);

  -- 4. every stuck retry, exactly as the dispatcher would key it
  FOR v_q IN
    SELECT q.id, q.campaign_target_id, q.touch_number, q.campaign_id, q.thread_key, q.to_phone_number,
           (q.metadata->>'spam_retry_generation')::int AS gen
      FROM public.send_queue q
     WHERE q.queue_status = 'queued' AND q.metadata->>'spam_retry_generation' IS NOT NULL
  LOOP
    rr := public.seller_logical_communication_get_or_create(${key('v_q.campaign_target_id', 'v_q.touch_number', '(v_q.gen + 1)')},
            'lck_v1', 'campaign_touch',
            jsonb_build_object('campaign_target_id', v_q.campaign_target_id, 'touch_number', v_q.touch_number::text,
              'campaign_id', v_q.campaign_id, 'thread_key', v_q.thread_key, 'to_phone_number', v_q.to_phone_number), '{}'::jsonb);
    tk := (rr->>'ok') || ':' || coalesce(rr->>'reason', CASE WHEN (rr->>'reused')::boolean THEN 'reused' ELSE 'created' END);
    tally := jsonb_set(tally, ARRAY[tk], to_jsonb(coalesce((tally->>tk)::int, 0) + 1));
  END LOOP;

  RAISE EXCEPTION 'S11_SUCCESSOR_PROOF %', jsonb_build_object(
    'retry_row', v_row.id, 'root', v_root_id,
    'r1', r1, 'r1b', r1b, 'r1c', r1c, 'a1', a1, 'r_root', r_root, 'a_root', a_root,
    'delivered_touch', v_del.id, 'rD', rD, 'rNew', rNew, 'rNew2', rNew2,
    'all_retries', tally,
    'unique_indexes', (SELECT jsonb_agg(indexname ORDER BY indexname) FROM pg_indexes
                        WHERE schemaname = 'public' AND tablename = 'seller_logical_communications' AND indexname LIKE 'uq_%'),
    'max_roots_per_touch', (SELECT max(n) FROM (SELECT count(*) n FROM public.seller_logical_communications
                        WHERE supersedes_communication_id IS NULL AND campaign_target_id IS NOT NULL
                        GROUP BY campaign_target_id, touch_number) z)
  )::text;
END
$proof$;
`;

const out = path.join(here, 's11-campaign-touch-successor-proof.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(process.cwd(), out)} (${sql.split('\n').length} lines)`);
